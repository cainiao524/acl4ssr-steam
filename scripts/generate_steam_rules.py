#!/usr/bin/env python3
from __future__ import annotations

from pathlib import Path
from urllib.request import Request, urlopen
import sys

STEAM_URL = "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Clash/Steam/Steam.list"
STEAM_CN_URL = "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Clash/SteamCN/SteamCN.list"

ROOT = Path(__file__).resolve().parents[1]
RULE_DIR = ROOT / "rules"
DOWNLOAD_OUT = RULE_DIR / "SteamDownload.list"
WEB_OUT = RULE_DIR / "SteamWeb.list"

# SteamCN 中这个规则更适合作为社区/创意工坊资源，而不是“游戏下载”。
FORCE_WEB = {
    "steamusercontent.com",
}

# SteamCN 大部分规则属于国内下载 CDN / 客户端连接。
# 此外，从 Steam 总表中自动识别国际游戏下载 CDN。
DOWNLOAD_HINTS = (
    "steampipe",
    "steamcontent",
    ".qtlglb.com",
    "steam.cdn.",
    ".content.steamchina.com",
    "edge.steam-dns.top.comcast.net",
    "f3b7q2p3.ssl.hwcdn.net",
)

REQUIRED_STEAM = {
    "steamcommunity.com",
    "steampowered.com",
    "steampipe.akamaized.net",
}
REQUIRED_STEAM_CN = {
    "steamcontent.com",
    "cm.steampowered.com",
}


def fetch(url: str) -> str:
    req = Request(url, headers={"User-Agent": "acl4ssr-steam-rule-generator/1.0"})
    with urlopen(req, timeout=30) as resp:
        if resp.status != 200:
            raise RuntimeError(f"HTTP {resp.status}: {url}")
        data = resp.read()
    text = data.decode("utf-8")
    if not text.strip():
        raise RuntimeError(f"上游返回空文件: {url}")
    return text


def parse(text: str) -> list[str]:
    result: list[str] = []
    seen: set[str] = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        # 只接受常规 Clash 域名规则，避免上游格式异常被直接发布。
        kind = line.split(",", 1)[0]
        if kind not in {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD"}:
            continue
        if line not in seen:
            seen.add(line)
            result.append(line)
    return result


def value_of(rule: str) -> str:
    parts = rule.split(",", 1)
    return parts[1].strip().lower() if len(parts) == 2 else ""


def has_value(rules: list[str], value: str) -> bool:
    value = value.lower()
    return any(value_of(r) == value for r in rules)


def is_download(rule: str, steam_cn_values: set[str]) -> bool:
    value = value_of(rule)

    if value in FORCE_WEB:
        return False

    # SteamCN 上游负责国内 CDN / 客户端连接。
    if value in steam_cn_values:
        return True

    # Steam 总表中的国际游戏下载 CDN 自动识别。
    return any(hint in value for hint in DOWNLOAD_HINTS)


def dedupe_keep_order(lines: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for line in lines:
        if line not in seen:
            seen.add(line)
            out.append(line)
    return out


def validate_sources(steam: list[str], steam_cn: list[str]) -> None:
    if len(steam) < 40:
        raise RuntimeError(f"Steam 上游规则异常：仅 {len(steam)} 条，拒绝覆盖")
    if len(steam_cn) < 10:
        raise RuntimeError(f"SteamCN 上游规则异常：仅 {len(steam_cn)} 条，拒绝覆盖")

    for value in REQUIRED_STEAM:
        if not has_value(steam, value):
            raise RuntimeError(f"Steam 上游缺少关键规则 {value}，拒绝覆盖")
    for value in REQUIRED_STEAM_CN:
        if not has_value(steam_cn, value):
            raise RuntimeError(f"SteamCN 上游缺少关键规则 {value}，拒绝覆盖")


def validate_outputs(download: list[str], web: list[str]) -> None:
    if len(download) < 15:
        raise RuntimeError(f"下载分组异常：仅 {len(download)} 条")
    if len(web) < 20:
        raise RuntimeError(f"网页分组异常：仅 {len(web)} 条")

    required_download = {
        "steamcontent.com",
        "steampipe.akamaized.net",
        "cm.steampowered.com",
        "steamserver.net",
    }
    required_web = {
        "steamcommunity.com",
        "steampowered.com",
        "steam-chat.com",
        "steamusercontent.com",
    }

    for value in required_download:
        if not has_value(download, value):
            raise RuntimeError(f"下载分组缺少关键规则 {value}")
    for value in required_web:
        if not has_value(web, value):
            raise RuntimeError(f"网页分组缺少关键规则 {value}")

    # 防止最关键的下载 CDN 被误分类到网页组。
    forbidden_web = {
        "steamcontent.com",
        "steampipe.akamaized.net",
        "cm.steampowered.com",
        "steamserver.net",
    }
    for value in forbidden_web:
        if has_value(web, value):
            raise RuntimeError(f"网页分组错误包含 {value}")


def render(title: str, lines: list[str]) -> str:
    header = [
        f"# NAME: {title}",
        "# GENERATED: automatically from blackmatrix7/ios_rule_script",
        "# DO NOT EDIT: generated by scripts/generate_steam_rules.py",
        f"# TOTAL: {len(lines)}",
        "",
    ]
    return "\n".join(header + lines) + "\n"


def main() -> int:
    steam = parse(fetch(STEAM_URL))
    steam_cn = parse(fetch(STEAM_CN_URL))
    validate_sources(steam, steam_cn)

    steam_cn_values = {value_of(r) for r in steam_cn}

    # 合并两个上游。SteamCN 中 FORCE_WEB 项即使不在 Steam 总表，也会进入网页组。
    all_rules = dedupe_keep_order(steam_cn + steam)

    download: list[str] = []
    web: list[str] = []

    for rule in all_rules:
        if is_download(rule, steam_cn_values):
            download.append(rule)
        else:
            web.append(rule)

    download = dedupe_keep_order(download)
    web = dedupe_keep_order(web)

    validate_outputs(download, web)

    RULE_DIR.mkdir(parents=True, exist_ok=True)
    DOWNLOAD_OUT.write_text(render("SteamDownload", download), encoding="utf-8", newline="\n")
    WEB_OUT.write_text(render("SteamWeb", web), encoding="utf-8", newline="\n")

    print(f"SteamDownload: {len(download)}")
    print(f"SteamWeb: {len(web)}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
